// InitSystemArticles initializes the default system articles
func InitSystemArticles(db *gorm.DB) error {
	var count int64
	if err := db.Model(&Article{}).Count(&count).Error; err != nil {
		return err
	}

	if count == 0 {
		articles := initSystemArticles()

		for _, v := range articles {
			v.Title = fmt.Sprintf(ArticleTitleTranslatePrefix, v.Symbol)
			v.Content = fmt.Sprintf(ArticleContentTranslatePrefix, v.Symbol)
		}
		if err := db.Create(&articles).Error; err != nil {
			return err
		}
	}

	return nil
}

