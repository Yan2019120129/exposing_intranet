// Article 系统文章管理
type Article struct {
	BaseModel
	AdminID uint        `gorm:"type:int unsigned not null;uniqueIndex:idx_admin_symbol;comment:管理ID" json:"adminId"`
	Symbol  string      `gorm:"type:varchar(50) not null;uniqueIndex:idx_admin_symbol;comment:标识" json:"symbol"`
	Cover   string      `gorm:"type:varchar(255);comment:封面" json:"cover"`
	Title   string      `gorm:"type:varchar(100) not null;comment:标题" json:"title"`
	Content string      `gorm:"type:text;comment:内容" json:"content"`
	Sort    uint8       `gorm:"type:tinyint unsigned not null;default:99;index;comment:排序" json:"sort"`
	Nums    uint        `gorm:"type:int unsigned not null;default:0;comment:浏览" json:"nums"`
	Type    int8        `gorm:"type:tinyint not null;default:1;index;comment:类型(1:默认文章)" json:"type"`
	Status  int8        `gorm:"type:tinyint not null;default:10;index;comment:状态(-1:禁用,10:启用)" json:"status"`
	Data    ArticleData `gorm:"type:json;comment:数据" json:"data"`
}

// ArticleData 文章数据
type ArticleData struct {
}

// Value implements the driver.Valuer interface
func (d ArticleData) Value() (driver.Value, error) {
	return json.Marshal(d)
}

// Scan implements the sql.Scanner interface
func (d *ArticleData) Scan(value interface{}) error {
	bytes, ok := value.([]byte)
	if !ok {
		return errors.New("type assertion to []byte failed")
	}

	return json.Unmarshal(bytes, &d)
}

